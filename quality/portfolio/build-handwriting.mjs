import fs from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import { prototypeDir } from "./support.mjs";

// The checked-in full bundle is the geometry source of truth. Rebuilding resolves
// existing references first, so no second copy of the large source is necessary.
const args = process.argv.slice(2);
const input = args.includes("--input")
  ? args[args.indexOf("--input") + 1]
  : path.join(prototypeDir, "handwriting-glyphs.js");
const source = await fs.readFile(input, "utf8");
const match = source.match(
  /window\.PORTFOLIO_HANDWRITING\s*=\s*([\s\S]*);\s*$/,
);
if (!match)
  throw new Error("Expected the portfolio handwriting data assignment");
const phrases = JSON.parse(match[1]);
const header =
  "/* Generated by quality/portfolio/build-handwriting.mjs; preserve exact path coordinates. */\n";

function expandReferences(svg) {
  const paths = new Map();
  svg = svg.replace(
    /<path id="([^"]+-geometry-\d+)" d="([^"]*)"\/>/g,
    (_, id, data) => {
      paths.set(id, data);
      return "";
    },
  );
  return svg.replace(
    /<use\b([^>]*?) href="#([^"]+)"\/>/g,
    (_, attributes, id) => {
      assert.ok(paths.has(id), `Missing local geometry ${id}`);
      return `<path${attributes} d="${paths.get(id)}"/>`;
    },
  );
}

function shareGeometry(svg) {
  const expanded = expandReferences(svg);
  const prefix = expanded.match(/<mask id="([^"]+)"/)[1];
  const geometries = new Map();
  const shared = expanded
    .replace(/<path\b([^>]*?)\/>/g, (_, attributes) => {
      const data = attributes.match(/\bd="([^"]*)"/)[1];
      const presentation = attributes.replace(/\s+d="[^"]*"/, "");
      if (!geometries.has(data))
        geometries.set(data, `${prefix}-geometry-${geometries.size}`);
      return `<use${presentation} href="#${geometries.get(data)}"/>`;
    })
    .replace(
      "<defs>",
      `<defs>${[...geometries].map(([data, id]) => `<path id="${id}" d="${data}"/>`).join("")}`,
    );
  // Exact equality of all expanded d attributes is stronger than numerical equality:
  // no rounding, point reduction, reordering, or independently filled subpaths.
  const paths = (value) =>
    [...value.matchAll(/\bd="([^"]*)"/g)].map((item) => item[1]);
  assert.deepEqual(paths(expandReferences(shared)), paths(expanded));
  return shared;
}

const full = Object.fromEntries(
  Object.entries(phrases).map(([phrase, svg]) => [phrase, shareGeometry(svg)]),
);
assert.ok(full["tell me more"], "Project contact phrase is required");
for (const [filename, data] of [
  ["handwriting-glyphs.js", full],
  ["handwriting-contact.js", { "tell me more": full["tell me more"] }],
]) {
  const output = `${header}window.PORTFOLIO_HANDWRITING = ${JSON.stringify(data)};\n`;
  const destination = path.join(prototypeDir, filename);
  if (args.includes("--check"))
    assert.equal(
      await fs.readFile(destination, "utf8"),
      output,
      `${filename} is stale`,
    );
  else await fs.writeFile(destination, output);
  console.log(
    `${filename}: ${Buffer.byteLength(output)} bytes${args.includes("--check") ? " (current)" : ""}`,
  );
}
