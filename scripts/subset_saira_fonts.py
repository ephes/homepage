"""Build the main site's Saira fonts from the portfolio's variable font files.

The portfolio ships Saira as full variable fonts (weight and width axes, ~170-200 KB
each). The main site only needs the weight axis, so this script pins the width axis
at 100 (normal) and splits each style into two files, like Google Fonts does:

* ``saira[-italic]-latin.woff2``: Basic Latin, Latin-1, common punctuation, arrows,
  euro sign and capital sharp s. Every page needs it; it is preloaded.
* ``saira[-italic]-latin-ext.woff2``: every other character in Saira (Latin Extended,
  Vietnamese, symbols). Browsers only fetch it when a page uses one of these characters.

It then rewrites the ``@font-face`` block between the ``saira-fonts`` markers in
``homepage/static/css/site-overrides.css`` with matching ``unicode-range`` values.

Run from the repository root:

    uvx --with brotli --from fonttools python scripts/subset_saira_fonts.py
"""

from __future__ import annotations

import re
import shutil
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIR = ROOT / "homepage/portfolio/static/portfolio/fonts"
TARGET_DIR = ROOT / "homepage/static/fonts"
CSS_FILE = ROOT / "homepage/static/css/site-overrides.css"

STYLES = {
    # file prefix: (source file, CSS font-style)
    "saira": ("saira-variable.woff2", "normal"),
    "saira-italic": ("saira-italic-variable.woff2", "italic"),
}

# Google Fonts' "latin" range plus the arrows U+2190-2193 and capital sharp s (U+1E9E).
CORE_RANGES = [
    (0x0000, 0x00FF),
    (0x0131, 0x0131),
    (0x0152, 0x0153),
    (0x02BB, 0x02BC),
    (0x02C6, 0x02C6),
    (0x02DA, 0x02DA),
    (0x02DC, 0x02DC),
    (0x0304, 0x0304),
    (0x0308, 0x0308),
    (0x0329, 0x0329),
    (0x1E9E, 0x1E9E),
    (0x2000, 0x206F),
    (0x20AC, 0x20AC),
    (0x2122, 0x2122),
    (0x2190, 0x2193),
    (0x2212, 0x2212),
    (0x2215, 0x2215),
    (0xFEFF, 0xFEFF),
    (0xFFFD, 0xFFFD),
]

CSS_START = "/* saira-fonts:start (generated by scripts/subset_saira_fonts.py, do not edit) */"
CSS_END = "/* saira-fonts:end */"


def in_core(codepoint: int) -> bool:
    return any(start <= codepoint <= end for start, end in CORE_RANGES)


def to_ranges(codepoints: list[int]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for cp in sorted(codepoints):
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((cp, cp))
    return ranges


def css_range(ranges: list[tuple[int, int]]) -> str:
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in ranges)


def build_subset(font: TTFont, codepoints: list[int], target: Path) -> None:
    options = subset.Options()
    options.layout_features = ["*"]
    options.flavor = "woff2"
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(target)


def font_face(file_name: str, style: str, ranges: list[tuple[int, int]]) -> str:
    return (
        "@font-face {\n"
        '  font-family: "Saira";\n'
        f'  src: url("../fonts/{file_name}") format("woff2");\n'
        f"  font-style: {style};\n"
        "  font-weight: 100 900;\n"
        "  font-display: optional;\n"
        f"  unicode-range: {css_range(ranges)};\n"
        "}\n"
    )


def main() -> None:
    TARGET_DIR.mkdir(parents=True, exist_ok=True)
    faces: list[str] = []
    for prefix, (source_name, style) in STYLES.items():
        # Keep the source's timestamp, so repeated runs write identical files.
        source = TTFont(SOURCE_DIR / source_name, recalcTimestamp=False)
        source_cmap = set(source.getBestCmap())
        pinned = instancer.instantiateVariableFont(source, {"wdth": 100})

        core = [cp for cp in source_cmap if in_core(cp)]
        # Private-use code points (icon-font territory) are left out of the extension file.
        ext = [cp for cp in source_cmap if not in_core(cp) and not 0xE000 <= cp <= 0xF8FF]
        for suffix, codepoints in (("latin", core), ("latin-ext", ext)):
            target = TARGET_DIR / f"{prefix}-{suffix}.woff2"
            build_subset(TTFont(_copy(pinned), recalcTimestamp=False), codepoints, target)
            built = set(TTFont(target).getBestCmap())
            missing = set(codepoints) - built
            if missing:
                raise SystemExit(f"{target.name} lacks {css_range(to_ranges(sorted(missing)))}")
            faces.append(font_face(target.name, style, to_ranges(codepoints)))
            print(f"{target.relative_to(ROOT)}: {len(built)} characters, {target.stat().st_size} bytes")

    shutil.copy(SOURCE_DIR / "SAIRA-LICENSE.txt", TARGET_DIR / "SAIRA-LICENSE.txt")

    css = CSS_FILE.read_text()
    block = CSS_START + "\n" + "\n".join(faces) + CSS_END
    pattern = re.compile(re.escape(CSS_START) + r".*?" + re.escape(CSS_END), re.S)
    if not pattern.search(css):
        raise SystemExit(f"Markers not found in {CSS_FILE}")
    CSS_FILE.write_text(pattern.sub(lambda _: block, css))
    print(f"Updated {CSS_FILE.relative_to(ROOT)}")


def _copy(font: TTFont) -> BytesIO:
    """Return an in-memory copy of a font, so each subset starts from the full font."""
    buffer = BytesIO()
    font.flavor = None
    font.save(buffer)
    buffer.seek(0)
    return buffer


if __name__ == "__main__":
    main()
